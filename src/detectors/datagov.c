static int datagov_fail(char **error, const char *message)
{
    if (error) *error = strdup(message);
    return -1;
}

static int datagov_verify(const br_scan_ctx *ctx, const char *key, br_result *result)
{
    /* The complete fixed-prefix + 40-byte ASCII key URL is 89 bytes + NUL.
     * Format BEFORE the source's known nil-context constructor failure. The
     * precision also permits the nil-context path's borrowed capture bytes. */
    char url[sizeof("https://api.ers.usda.gov/data/arms/state?api_key=") + 40];
    int n = snprintf(url, sizeof(url), "https://api.ers.usda.gov/data/arms/state?api_key=%.40s", key);
    if (n < 0 || (size_t)n >= sizeof(url)) return -1;
    if (!ctx) return 0; /* Caller handles the constructor's candidate skip. */
    const br_http_request request = {
        .method = "GET", .url = url, .profile = BR_HTTP_SANE,
        .detector_type = result->detector_type,
    };
    br_http_response response = {0};
    char *transport_error = NULL;
    /* Source suppresses ALL Do errors. ABI1 also mixes setup/allocation into
     * this domain: suppress it whole, with no setter or text classification. */
    if (br_http_send(ctx, &request, &response, &transport_error) == 0)
        result->verified = response.status >= 200 && response.status < 300;
    /* Keep the complete stack URL alive through send AND release. Source
     * scan-defers Close ONLY, ignoring bodies/read errors. Eager buffering/
     * release, full native client and global engine/output parity stay partial. */
    br_http_release(ctx, &response);
    free(transport_error);
    return 0;
}

typedef struct { br_slice input; char *error; } datagov_skipped;

static int datagov_skip(void *user, const br_span *groups, size_t ngroups)
{
    datagov_skipped *skipped = user;
    if (ngroups < 2 || groups[1].begin == SIZE_MAX || groups[1].end > skipped->input.len ||
        groups[1].end < groups[1].begin || groups[1].end - groups[1].begin != 40)
        return datagov_fail(&skipped->error, "invalid DataGov capture");
    br_slice key = {skipped->input.data + groups[1].begin, 40};
    br_result result = {0};
    /* br_scan_key's verifier has no candidate-skip outcome. Only this known
     * constructor branch needs local handling: allocate finding resources,
     * prepare the URL, then discard without an invented result push. */
    int rc = 0;
    if (br_finding_key_bytes(&result, 404, key, "key") != 0)
        rc = datagov_fail(&skipped->error, "cannot create DataGov result");
    if (rc == 0 && datagov_verify(NULL, (const char *)key.data, &result) != 0)
        rc = datagov_fail(&skipped->error, "cannot format DataGov verification URL");
    br_result_clear(&result);
    return rc == 0 ? 0 : -1;
}

static int datagov_scan(const br_detector *detector, const br_scan_ctx *ctx, bool verify,
                        br_slice input, br_results *out, char **error)
{
    if (error) *error = NULL;
    if (!detector || !detector->state || !out || (!input.data && input.len))
        return datagov_fail(error, "invalid or uninitialized DataGov scan");
    if (verify && !ctx) {
        datagov_skipped skipped = {input, NULL};
        char *regex_error = NULL;
        int rc = br_regex_each(detector->state, input, datagov_skip, &skipped, &regex_error);
        if (skipped.error) { free(regex_error); regex_error = skipped.error; }
        if (error) *error = regex_error;
        else free(regex_error);
        return rc == 0 ? 0 : -1; /* This path never changes caller findings. */
    }
    /* TrimSpace is a no-op for the ASCII capture. Shared occurrence scanning
     * supplies result fields, preserves duplicates and rolls back only this
     * invocation's findings. Normalize positive regex/resource errors to -1. */
    int rc = br_scan_key(detector, ctx, verify, input, out, "key", datagov_verify, error);
    return rc == 0 ? 0 : -1;
}

static const char *const datagov_keywords[] = {"data.gov"};
static br_detector datagov_detector = {
    .type = 404, .version = 0, .name = "DataGov", .custom_name = "",
    .description = "Data.gov provides access to datasets generated by the U.S. government. The API key can be used to access and retrieve data from these datasets.",
    .keywords = datagov_keywords, .nkeywords = 1,
    .max_secret_size = -1, .start_offset = -1, .max_credential_span = -1,
    .scan = datagov_scan,
};

int br_datagov_init(const br_detector **out, char **error)
{
    if (error) *error = NULL;
    if (!out) return datagov_fail(error, "invalid DataGov detector output");
    *out = NULL;
    /* Dispatch remains literal data.gov. PrefixRegex intentionally does NOT
     * escape that dot: extraction accepts any one non-LF rune in its place,
     * and only the keyword is case-insensitive, not the mixed-alnum capture. */
    if (br_key_pattern_init(&datagov_detector, "\\b([a-zA-Z0-9]{40})\\b", error) != 0) return -1;
    *out = &datagov_detector;
    return 0;
}
