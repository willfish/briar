static char key1[41], key2[41];
static size_t fail_alloc_size, fail_alloc_after, fail_part_after;
static bool fail_agent_copy;

/* Target the actual finding/capture/shared-send resources and positive helper
 * returns. There is no heap URL, provider transport seam or setter substitute. */
void *malloc(size_t size)
{
    if (fail_alloc_after && size == fail_alloc_size && --fail_alloc_after == 0) return NULL;
    return calloc(1, size);
}

char *strdup(const char *text)
{
    if (fail_agent_copy && !strcmp(text, "TruffleHog")) { fail_agent_copy = false; return NULL; }
    size_t len = strlen(text) + 1; char *copy = malloc(len);
    if (copy) memcpy(copy, text, len);
    return copy;
}

int json_object_object_add(struct json_object *object, const char *name, struct json_object *value)
{
    if (fail_part_after && --fail_part_after == 0) return 1;
    return json_object_object_add_ex(object, name, value, 0);
}

static br_slice text(const char *s) { return (br_slice){(const unsigned char *)s, strlen(s)}; }

static const br_detector *descriptor(void)
{
    const br_detector *detector = NULL, *again = NULL; char *error = NULL;
    CHECK(BR_ABI_REVISION == 1);
    CHECK(br_datagov_init(NULL, &error) == -1 && error && !strcmp(error, "invalid DataGov detector output"));
    free(error); error = NULL;
    CHECK(br_datagov_init(NULL, NULL) == -1);
    CHECK(br_datagov_init(&detector, &error) == 0 && detector && !error);
    CHECK(br_datagov_init(&again, NULL) == 0 && again == detector);
    CHECK(detector->type == 404 && detector->version == 0 && !strcmp(detector->name, "DataGov"));
    CHECK(detector->custom_name && !*detector->custom_name);
    CHECK(!strcmp(detector->description, "Data.gov provides access to datasets generated by the U.S. government. The API key can be used to access and retrieve data from these datasets."));
    CHECK(detector->nkeywords == 1 && !strcmp(detector->keywords[0], "data.gov")); /* Dispatch is STILL literal. */
    CHECK(detector->max_secret_size == -1 && detector->start_offset == -1 && detector->max_credential_span == -1);
    CHECK(detector->state && detector->scan && !detector->clean && !detector->clean_always && !detector->false_positive);
    CHECK(!detector->validate_endpoints && !detector->cloud_endpoint);
    return detector;
}

static void check_result(const br_result *result, const char *key, bool verified)
{
    test_key_result(result, 404, key, "key");
    CHECK(result->verified == verified && !result->verification_error);
}

static void extraction_case(const br_detector *detector, br_slice input, const char *expected)
{
    test_http http = {0}; br_transport transport = test_transport(&http); br_scan_ctx ctx = {.transport = &transport};
    br_results results = test_scan(detector, &ctx, false, input.data, input.len);
    CHECK(results.len == (expected ? 1u : 0u) && !http.calls && !http.releases);
    if (expected) check_result(&results.items[0], expected, false);
    br_results_clear(&results);
}

static void extraction(const br_detector *detector)
{
    char input[512], changed[42];
    const struct { const char *format; bool match; } cases[] = {
        {"data.gov %s", true}, {"DaTa.GoV:'%s'", true}, {"preDATA.GOVsuffix\r\n%s", true},
        {"dataXgov %s", true}, {"data/gov %s", true}, {"data\rgov %s", true},
        {"data\xc3\xa9gov %s", true}, {"data\xf0\x9f\x98\x80gov %s", true},
        {"data\ngov %s", false}, {"datagov %s", false}, {"dataXYgov %s", false},
        {"%s data.gov", false}, {"%s", false}, {"data.gov%s", false},
        {"data.gov x%s", false}, {"data.gov _%s", false}, {"data.gov %sx", false}, {"data.gov %s_", false},
        {"data.gov .%s!", true}, {"data.gov \xc3\xa9%s\xc3\xa9", true},
    };
    for (size_t i = 0; i < sizeof(cases) / sizeof(cases[0]); ++i) {
        snprintf(input, sizeof(input), cases[i].format, key1);
        extraction_case(detector, text(input), cases[i].match ? key1 : NULL);
    }
    snprintf(input, sizeof(input), "data.gov %.39s", key1); extraction_case(detector, text(input), NULL);
    snprintf(input, sizeof(input), "data.gov %sA", key1); extraction_case(detector, text(input), NULL);
    for (size_t i = 0; i < 3; ++i) {
        memcpy(changed, key1, sizeof(key1)); changed[13] = "_-."[i];
        snprintf(input, sizeof(input), "data.gov %s", changed); extraction_case(detector, text(input), NULL);
    }
    memset(changed, 'A', 40); changed[40] = '\0';
    snprintf(input, sizeof(input), "data.gov %s", changed); extraction_case(detector, text(input), changed); /* No entropy/local filter. */
    for (size_t gap = 40; gap <= 41; ++gap) {
        for (int unicode = 0; unicode < 2; ++unicode) {
            memcpy(input, "data.gov", 8); size_t at = 8;
            for (size_t r = 0; r < gap; ++r) {
                if (unicode) { memcpy(input + at, "\xc3\xa9", 2); at += 2; }
                else input[at++] = '.';
            }
            memcpy(input + at, key1, sizeof(key1));
            extraction_case(detector, (br_slice){(const unsigned char *)input, at + 40}, gap == 40 ? key1 : NULL);
        }
    }
    memcpy(input, "data\0gov ", 9); memcpy(input + 9, key1, sizeof(key1));
    extraction_case(detector, (br_slice){(const unsigned char *)input, 49}, key1); /* Wildcard also matches a valid NUL rune. */
    input[4] = (char)0xff;
    extraction_case(detector, (br_slice){(const unsigned char *)input, 49}, NULL); /* Invalid-byte barrier, not normalization. */
    int n = snprintf(input, sizeof(input), "\xff\ndata.gov %s\n\xff", key1);
    extraction_case(detector, (br_slice){(const unsigned char *)input, (size_t)n}, key1); /* No whole-input UTF-8 guard. */
    extraction_case(detector, (br_slice){0}, NULL);
}

typedef struct {
    const char *const *keys; size_t count;
    const char *agent, *borrowed_url, *current_key;
    const br_scan_ctx *original;
} expected_http;

static void inspect_request(test_http *http, const br_scan_ctx *ctx, const br_http_request *request)
{
    expected_http *expected = http->user;
    CHECK(ctx && ctx == expected->original && http->calls <= expected->count); /* Source USES scan context. */
    const char *key = expected->keys[http->calls - 1];
    const char prefix[] = "https://api.ers.usda.gov/data/arms/state?api_key=";
    CHECK(!strcmp(request->method, "GET") && request->profile == BR_HTTP_SANE);
    CHECK(request->timeout_ms == 5000 && request->detector_type == 404);
    CHECK(strlen(prefix) == 49 && strlen(request->url) == 89 && request->url[89] == '\0');
    CHECK(!memcmp(request->url, prefix, 49) && !memcmp(request->url + 49, key, 40));
    CHECK(!request->body.data && !request->body.len && !request->dedup_key.data && !request->dedup_key.len);
    CHECK(request->nheaders == 1 && !strcmp(request->headers[0].name, "User-Agent"));
    CHECK(!strcmp(request->headers[0].value, expected->agent)); /* No Type/Accept/Auth/key/CL headers. */
    expected->borrowed_url = request->url; expected->current_key = key;
}

static void release_response(void *user, br_http_response *response)
{
    test_http *http = user; expected_http *expected = http->user;
    if (expected && expected->borrowed_url) {
        CHECK(strlen(expected->borrowed_url) == 89 && expected->borrowed_url[89] == '\0');
        CHECK(!memcmp(expected->borrowed_url + 49, expected->current_key, 40)); /* Stack URL survives release. */
        expected->borrowed_url = NULL;
    }
    test_http_release(user, response);
}

static br_transport transport_for(test_http *http)
{
    return (br_transport){http, test_http_send, release_response};
}

static void occurrences(const br_detector *detector)
{
    char input[256]; int n = snprintf(input, sizeof(input), "data.gov %s\ndataXgov %s\nDaTa.GoV %s", key1, key2, key1);
    const char *keys[] = {key1, key2, key1};
    expected_http expected = {.keys = keys, .count = 3, .agent = "TruffleHog datagov-offline"};
    test_http http = {.response = {.status = 204, .body_error = "ignored"}, .inspect = inspect_request, .user = &expected};
    br_transport transport = transport_for(&http); br_scan_ctx ctx = {.transport = &transport, .user_agent = "datagov-offline"}; expected.original = &ctx;
    br_results results = test_scan(detector, &ctx, true, input, (size_t)n);
    CHECK(results.len == 3 && http.calls == 3 && http.releases == 3);
    for (size_t i = 0; i < results.len; ++i) check_result(&results.items[i], keys[i], true); /* No uniqueness/cache. */
    br_results_clear(&results);
    results = test_scan(detector, NULL, true, input, (size_t)n);
    CHECK(!results.len && http.calls == 3 && http.releases == 3); br_results_clear(&results); /* Known constructor skip, not an unverified finding. */
    results = test_scan(detector, NULL, false, input, (size_t)n);
    CHECK(results.len == 3);
    for (size_t i = 0; i < results.len; ++i) check_result(&results.items[i], keys[i], false);
    br_results_clear(&results);
}

static void verification(const br_detector *detector)
{
    char input[128]; int n = snprintf(input, sizeof(input), "data.gov %s", key1);
    const char *keys[] = {key1}; expected_http expected = {.keys = keys, .count = 1, .agent = "TruffleHog"};
    static const unsigned char body[] = {0, 0xff, '{', '!'};
    const struct { int status, rc; const char *cause, *read_error; bool verified; } cases[] = {
        {199, 0, NULL, NULL, false}, {200, 0, NULL, NULL, true}, {201, 0, NULL, "ignored", true},
        {204, 0, NULL, "", true}, {299, 0, NULL, "ignored", true}, {300, 0, NULL, NULL, false},
        {401, 0, NULL, "ignored", false}, {403, 0, NULL, NULL, false}, {500, 0, NULL, NULL, false},
        {200, -1, "synthetic timeout", "ignored", false}, {200, 1, "net/http: nil Context", NULL, false},
        {200, 1, "out of memory constructing HTTP headers", NULL, false}, {200, 1, NULL, NULL, false},
    };
    for (size_t i = 0; i < sizeof(cases) / sizeof(cases[0]); ++i) {
        test_http http = {.response = {.status = cases[i].status, .body = {body, sizeof(body)}, .body_error = cases[i].read_error},
                          .send_rc = cases[i].rc, .send_error = cases[i].cause, .inspect = inspect_request, .user = &expected};
        br_transport transport = transport_for(&http); br_scan_ctx ctx = {.transport = &transport}; expected.original = &ctx;
        br_results results = test_scan(detector, &ctx, true, input, (size_t)n);
        CHECK(results.len == 1 && http.calls == 1 && http.releases == 1);
        check_result(&results.items[0], key1, cases[i].verified); br_results_clear(&results);
    }
}

static bool cancelled(void *user) { ++*(size_t *)user; return true; }

static void suppressed_setup(const br_detector *detector)
{
    char input[128]; int n = snprintf(input, sizeof(input), "data.gov %s", key1);
    test_http http = {0}; br_transport transport = test_transport(&http); size_t cancellations = 0;
    br_scan_ctx contexts[] = {
        {0}, {.transport = &transport, .cancelled = cancelled, .cancel_user = &cancellations},
        {.transport = &transport, .deadline_monotonic_ms = 1}, {.transport = &transport, .user_agent = "bad\r\nagent"},
        {.transport = &transport},
    };
    for (size_t i = 0; i < sizeof(contexts) / sizeof(contexts[0]); ++i) {
        http.calls = http.releases = 0; if (i == 4) fail_agent_copy = true;
        br_results results = test_scan(detector, &contexts[i], true, input, (size_t)n);
        CHECK(results.len == 1 && !http.calls && http.releases == (i ? 1u : 0u) && !fail_agent_copy);
        check_result(&results.items[0], key1, false); br_results_clear(&results);
    }
    CHECK(cancellations == 1); /* Cancellation is NOT cleared or ignored. */
}

static br_results prior_results(void)
{
    br_result prior = {.detector_type = 12345, .verified = true};
    prior.raw.data = malloc(4); CHECK(prior.raw.data); memcpy(prior.raw.data, "keep", 4); prior.raw.len = 4;
    prior.verification_error = strdup("caller-owned"); CHECK(prior.verification_error);
    br_results results = {0}; CHECK(br_results_push(&results, &prior) == 0); return results;
}

static void check_prior(const br_results *results, br_result prior)
{
    CHECK(results->len == 1 && results->items[0].detector_type == 12345 && results->items[0].verified);
    CHECK(results->items[0].raw.data == prior.raw.data && results->items[0].raw.len == 4 && !memcmp(prior.raw.data, "keep", 4));
    CHECK(results->items[0].verification_error == prior.verification_error && !strcmp(prior.verification_error, "caller-owned"));
}

static void fatal_resources(const br_detector *detector)
{
    char input[256]; int n = snprintf(input, sizeof(input), "data.gov %s\ndata.gov %s", key1, key2);
    br_slice data = {(const unsigned char *)input, (size_t)n};
    br_results results = prior_results(); br_result prior = results.items[0]; char *error = NULL;
    test_http http = {.response = {.status = 200}}; br_transport transport = test_transport(&http); br_scan_ctx ctx = {.transport = &transport};
    fail_part_after = 2;
    CHECK(detector->scan(detector, &ctx, true, data, &results, &error) == -1);
    CHECK(error && !strcmp(error, "out of memory creating detector result") && !fail_part_after && http.calls == 1 && http.releases == 1);
    check_prior(&results, prior); free(error); error = NULL; /* Shared scan rolls back only its first appended finding. */
    fail_part_after = 2;
    CHECK(detector->scan(detector, NULL, true, data, &results, &error) == -1);
    CHECK(error && !strcmp(error, "cannot create DataGov result") && !fail_part_after);
    check_prior(&results, prior); free(error); error = NULL; /* Finding failures remain fatal even in constructor-skip path. */
    fail_alloc_size = 40; fail_alloc_after = 1;
    CHECK(detector->scan(detector, NULL, true, data, &results, &error) == -1);
    CHECK(error && !strcmp(error, "cannot create DataGov result") && !fail_alloc_after);
    check_prior(&results, prior); free(error); error = NULL;
    fail_alloc_size = 41; fail_alloc_after = 1;
    CHECK(detector->scan(detector, &ctx, true, data, &results, &error) == -1);
    CHECK(error && !strcmp(error, "out of memory copying detector key") && !fail_alloc_after);
    check_prior(&results, prior); free(error); error = NULL;
    /* Both entry paths normalize the real regex workspace helper's +1. */
    fail_alloc_size = 2 * sizeof(br_span); fail_alloc_after = 1;
    CHECK(detector->scan(detector, &ctx, true, data, &results, NULL) == -1 && !fail_alloc_after); check_prior(&results, prior);
    fail_alloc_after = 1;
    CHECK(detector->scan(detector, NULL, true, data, &results, NULL) == -1 && !fail_alloc_after); check_prior(&results, prior);
    size_t capacity = results.cap; results.cap = 0;
    CHECK(detector->scan(detector, NULL, true, data, &results, &error) == 0 && !error); check_prior(&results, prior); /* Skips NEVER attempt a result push. */
    CHECK(detector->scan(detector, NULL, false, data, &results, &error) == -1);
    CHECK(error && !strcmp(error, "out of memory appending detector result")); results.cap = capacity;
    check_prior(&results, prior); free(error); br_results_clear(&results);
    http.calls = http.releases = 0;
    results = test_scan(detector, &ctx, true, input, (size_t)n);
    CHECK(results.len == 2 && http.calls == 2 && http.releases == 2);
    check_result(&results.items[0], key1, true); check_result(&results.items[1], key2, true);
    br_results_clear(&results);
}

