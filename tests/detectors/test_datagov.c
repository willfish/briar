{
    test_secret(key1, 40, 0); test_secret(key2, 40, 9); key1[0] = 'Z'; key1[8] = 'A'; key2[7] = 'K';
    const br_detector *detector = descriptor();
    extraction(detector); occurrences(detector); verification(detector); suppressed_setup(detector); fatal_resources(detector);
    return test_finish("DataGov wildcard keyword + mixed-alnum occurrences + exact USDA URL + context skips + shared rollback");
}
