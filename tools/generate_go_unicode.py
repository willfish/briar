#!/usr/bin/env python3
"""Extract the selected pinned Go 1.26.7 Unicode 15.0 ranges without downloading.

Pass src/unicode/tables.go from the pinned Go source. --check compares the
maintained generated header without rewriting it. See NOTICE for attribution.
"""

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = "6a88d48746c4b2c471cc04ae40559694b734770212e6f5ea5f1962adb0c0bdb1"
TABLES = (("Ll", "lower"), ("Lu", "upper"), ("N", "number"),
          ("P", "punct"), ("S", "symbol"), ("White_Space", "space"))
OUTPUT = ROOT / "src/go_unicode_tables.h"


def generate(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("Unicode source does not match pinned Go 1.26.7")
    text = source.decode("utf-8")
    lines = ["/* SPDX-License-Identifier: BSD-3-Clause */",
             "/* Copyright 2009 The Go Authors. All rights reserved.",
             " * Generated by tools/generate_go_unicode.py; do not edit.",
             " * Go e3336a22ad3f0a90bd252c95d8b5544e02674205, Unicode 15.0.0.",
             " * Source: src/unicode/tables.go, SHA-256 " + SOURCE_SHA256 + ".",
             " * See LICENSES/BSD-3-Clause-Go.txt and NOTICE. */",
             "#ifndef BRIAR_GO_UNICODE_TABLES_H", "#define BRIAR_GO_UNICODE_TABLES_H", ""]
    for source_name, native_name in TABLES:
        match = re.search(r"var _" + source_name + r" = &RangeTable\{(.*?)\n\}", text, re.S)
        if not match:
            raise ValueError("missing Unicode table " + source_name)
        entries = [tuple(int(part, 0) for part in row) for row in re.findall(
            r"\{(0x[0-9a-f]+), (0x[0-9a-f]+), ([0-9]+)\}", match[1])]
        if not entries:
            raise ValueError("empty Unicode table " + source_name)
        previous = -1
        lines.append("static const unicode_range go_" + native_name + "[] = {")
        for lo, hi, stride in entries:
            if not (previous < lo <= hi <= 0x10ffff and stride > 0 and (hi - lo) % stride == 0):
                raise ValueError("invalid or unordered Unicode range " + source_name)
            lines.append(f"    {{0x{lo:06x}, 0x{hi:06x}, {stride}}},")
            previous = hi
        lines.extend(["};", ""])
    case_table = re.search(r"var _CaseRanges = \[\]CaseRange\{(.*?)\n\}", text, re.S)
    if not case_table:
        raise ValueError("missing Unicode case ranges")
    rows = re.findall(r"\{(0x[0-9A-F]+), (0x[0-9A-F]+), d\{([^,]+), ([^,]+), ([^}]+)\}\}", case_table[1])
    if not rows:
        raise ValueError("empty Unicode case ranges")
    lines.append("static const unicode_case_range go_lower_case[] = {")
    previous = -1
    for lo_text, hi_text, _, lower_text, _ in rows:
        lo, hi = int(lo_text, 0), int(hi_text, 0)
        delta = 0x110000 if lower_text == "UpperLower" else int(lower_text)
        if not (previous < lo <= hi <= 0x10ffff):
            raise ValueError("invalid or unordered Unicode case range")
        previous = hi
        # Zero lower deltas are identity, which the native lookup returns anyway.
        if delta:
            lines.append(f"    {{0x{lo:06x}, 0x{hi:06x}, {delta}}},")
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.source.read_bytes())
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("generated Unicode ranges differ")
        print("Pinned Go Unicode ranges match")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
